// Real macOS helper + app lifecycle, using disposable fixtures and no model calls.
import assert from "node:assert/strict";
import { mkdtemp, mkdir, readFile, writeFile, rm, symlink } from "node:fs/promises";
import { tmpdir } from "node:os";
import path from "node:path";
import { createServer } from "node:http";
import { createIntegrations } from "../sidecar/integrations.ts";
import { fileSecrets } from "../sidecar/settings.ts";
import { sandboxHelper } from "../sidecar/sandbox-status.ts";

const binaryPath = process.env.VAK_SANDBOX_BIN ?? path.resolve("../sandbox/target/release/vaksb");
assert.equal(process.platform, "darwin", "This evidence requires macOS Seatbelt");
assert.equal((await sandboxHelper(binaryPath)).compatible, true, "Rebuild the helper first");
const root = await mkdtemp(path.join(tmpdir(), "vak-sandbox-check-"));
const workspace = path.join(root, "project");
await mkdir(workspace); await mkdir(path.join(root, "logs"));
await writeFile(path.join(workspace, "sample.txt"), "original\n");
await writeFile(path.join(workspace, ".env"), "FIXTURE_ONLY=not-a-real-secret\n");
const outside = path.join(root, "outside.txt");
await writeFile(outside, "untouched\n");
const before = { enabled: process.env.VAK_SANDBOX_ENABLED, workspace: process.env.VAK_SANDBOX_WORKSPACE };
let decision: "allow" | "deny" = "deny", approvals = 0, requests = 0;
const listener = createServer((_, res) => { requests++; res.end("unexpected"); });
await new Promise<void>(resolve => listener.listen(0, "127.0.0.1", resolve));
const port = (listener.address() as { port: number }).port;
process.env.VAK_SANDBOX_ENABLED = "true"; process.env.VAK_SANDBOX_WORKSPACE = workspace;
let observed = "";
const integrations = createIntegrations({ observe: (_request, result) => { observed = result.text; }, dataDir: root, secrets: fileSecrets(path.join(root, "settings.env")), vakSandbox: { enabled: true, binaryPath }, approve: async () => { approvals++; return decision; } });
try {
  const tool = (await integrations.toolsFor("sandbox-proof")).find(t => t.spec.name.includes("run_command"))!;
  assert.ok(tool, "Actual execution tool must be offered");
  const command = { command: "/bin/sh", args: ["-c", "cat sample.txt; printf changed > sample.txt; test ! -e .env; printf ' copy-only\\n'"] };
  const denied = await tool.execute(command, {});
  assert.match(JSON.stringify(denied), /declined/); assert.equal(approvals, 1);
  decision = "allow";
  const success = await tool.execute(command, {});
  assert.match(JSON.stringify(success), /original/); assert.match(JSON.stringify(success), /exit code: 0/);
  assert.equal(await readFile(path.join(workspace, "sample.txt"), "utf8"), "original\n");
  console.log("PASS: real lifecycle approval, command result, excluded .env, original project unchanged");
  const containment = await tool.execute({ command: "/bin/sh", args: ["-c", 'cat "$1"; printf changed > "$1"; /usr/bin/curl --noproxy "*" --connect-timeout 1 --max-time 2 "$2"', "check", outside, `http://127.0.0.1:${port}`] }, {});
  assert.equal(typeof containment === "object" && containment.isError, true);
  assert.match(JSON.stringify(containment), /Operation not permitted|Permission denied|Failed to connect|Couldn't connect/);
  assert.equal(await readFile(outside, "utf8"), "untouched\n"); assert.equal(requests, 0);
  console.log("PASS: outside read/write denied and loopback network blocked");
  const environment = await tool.execute({ command: "/usr/bin/env", args: [] }, {});
  assert.doesNotMatch(JSON.stringify(environment), /OPENAI_API_KEY|TELEGRAM_BOT_TOKEN|VAK_SANDBOX_WORKSPACE/);
  const invalid = await tool.execute({ command: "/bin/pwd", args: [], workingDirectory: "../" }, {});
  assert.match(JSON.stringify(invalid), /relative path/);
  await symlink(outside, path.join(workspace, "escape.txt"));
  const escape = await tool.execute({ command: "/bin/pwd", args: [] }, {});
  assert.match(JSON.stringify(escape), /link that escapes/);
  await rm(path.join(workspace, "escape.txt"));
  process.env.VAK_SANDBOX_ENABLED = "false";
  const disabled = await tool.execute(command, {});
  assert.match(JSON.stringify(disabled), /disabled/);
  process.env.VAK_SANDBOX_ENABLED = "true";
  const missing = createIntegrations({ dataDir: root, secrets: fileSecrets(path.join(root, "settings.env")), vakSandbox: { enabled: true, binaryPath: path.join(root, "missing-helper") }, approve: async () => "allow" });
  const missingTool = (await missing.toolsFor("missing")).find(t => t.spec.name.includes("run_command"))!;
  const missingResult = await missingTool.execute(command, {});
  assert.equal(typeof missingResult === "object" && missingResult.isError, true);
  await missing.stopAll();
  const log = await readFile(path.join(root, "logs/tools.jsonl"), "utf8");
  assert.match(log, /"decision":"denied"/); assert.match(log, /"decision":"approved"/);
  console.log("PASS: minimal environment, path rejection, global off, missing-helper fail closed, audit log");
  const realmTools = await integrations.toolsFor("realm-proof");
  async function realmCall(name: string, args: Record<string, unknown>, fail = false): Promise<any> {
    observed = "";
    const tool = realmTools.find(t => t.spec.name.endsWith(`__${name}`))!;
    assert.ok(tool, `Agent tool ${name} is available`);
    const result = await tool.execute(args, {});
    if (fail) { assert.equal(typeof result === "object" && result.isError, true); return result; }
    assert.ok(!(typeof result === "object" && result.isError), JSON.stringify(result));
    return JSON.parse(observed);
  }
  const created = await realmCall("create_realm", {}), realmId = created.realm_id;
  const run = await realmCall("run_in_realm", { realmId, command: "/bin/sh", args: ["-c", "printf durable > sample.txt; printf new > added.txt"] });
  assert.equal(run.result.exit_code, 0);
  assert.equal(await readFile(path.join(workspace, "sample.txt"), "utf8"), "original\n");
  const next = await realmCall("run_in_realm", { realmId, command: "/bin/cat", args: ["sample.txt"] });
  assert.equal(next.result.stdout, "durable");
  const review = await realmCall("snapshot_realm", { realmId });
  assert.equal(review.can_promote, true); assert.equal(review.total, 2);
  const candidate = await realmCall("read_realm_file", { realmId, path: "sample.txt" });
  assert.equal(candidate.text, "durable");
  const paths = review.changes.map((c: { path: string }) => c.path);
  decision = "deny";
  const promotionTool = realmTools.find(t => t.spec.name.endsWith("__promote_realm"))!;
  const refused = await promotionTool.execute({ realmId, fingerprint: review.fingerprint, paths }, {});
  assert.match(JSON.stringify(refused), /declined/);
  assert.equal(await readFile(path.join(workspace, "sample.txt"), "utf8"), "original\n");
  decision = "allow";
  const receipt = await realmCall("promote_realm", { realmId, fingerprint: review.fingerprint, paths });
  assert.equal(receipt.phase, "committed"); assert.equal(await readFile(path.join(workspace, "sample.txt"), "utf8"), "durable");
  const reopened = createIntegrations({ observe: (_request, result) => { observed = result.text; }, dataDir: root, secrets: fileSecrets(path.join(root, "settings.env")), vakSandbox: { enabled: true, binaryPath }, approve: async () => "allow" });
  const reloadedTools = await reopened.toolsFor("restarted-realm");
  const resumed = await reloadedTools.find(t => t.spec.name.endsWith("__run_in_realm"))!.execute({ realmId, command: "/bin/cat", args: ["added.txt"] }, {});
  assert.match(JSON.stringify(resumed), /new/);
  await reopened.stopAll();
  await realmCall("rollback_realm", { realmId, transactionId: receipt.transaction_id, paths: receipt.paths });
  assert.equal(await readFile(path.join(workspace, "sample.txt"), "utf8"), "original\n");
  await assert.rejects(readFile(path.join(workspace, "added.txt")));
  const stale = await realmCall("snapshot_realm", { realmId });
  await writeFile(path.join(workspace, "sample.txt"), "user edit");
  await realmCall("promote_realm", { realmId, fingerprint: stale.fingerprint, paths: stale.changes.map((c: { path: string }) => c.path) }, true);
  assert.equal(await readFile(path.join(workspace, "sample.txt"), "utf8"), "user edit");
  await realmCall("destroy_realm", { realmId });
  assert.equal((await realmCall("list_realms", {})).length, 0);
  console.log("PASS: agent Realm create, repeated writes/runs, review/file reads, denied promotion, exact promotion, restart/resume, rollback, conflict refusal and destroy");

} finally {
  await integrations.stopAll(); listener.close();
  for (const [name, value] of [["VAK_SANDBOX_ENABLED", before.enabled], ["VAK_SANDBOX_WORKSPACE", before.workspace]]) { if (value === undefined) delete process.env[name!]; else process.env[name!] = value; }
  await rm(root, { recursive: true, force: true });
}
